def next_exploration_point(
    robot_id: int,
    step: int,
) -> pygame.Vector2:

    points = EXPLORATION_POINTS[
        robot_id
    ]

    x, y = points[
        step % len(points)
    ]

    return pygame.Vector2(
        x,
        y,
    )
